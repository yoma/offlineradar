/**
 * Regenerate data/be-places.ts: every Belgian postcode place (municipalities
 * and deelgemeenten) with coordinates.
 *
 * Source: spatie/belgian-cities-geocoded (MIT, © Spatie bvba), built on the
 * bpost postcode list.
 * Usage: npx tsx scripts/build-be-places.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const SOURCE =
  "https://raw.githubusercontent.com/spatie/belgian-cities-geocoded/master/belgian-cities-geocoded.csv";

// Joining words that the source title-cases (“Braine-Le-ChÂteau”).
const SMALL_WORDS = new Set([
  "le", "la", "les", "sur", "en", "lez", "lès", "du", "de", "des", "aux",
  "au", "sous", "à", "et", "aan", "op", "den", "der", "ter", "ten", "te",
  "bij", "in",
]);

function cleanName(raw: string): string {
  // Accented capitals inside a word are an encoding artefact: “LiÈge”.
  let name = raw.replace(/(\p{L})([À-Þ])/gu, (_, a: string, b: string) =>
    a + b.toLowerCase(),
  );
  name = name
    .split("-")
    .map((part, index) =>
      index > 0 && SMALL_WORDS.has(part.toLowerCase()) ? part.toLowerCase() : part,
    )
    .join("-")
    .replace(/-L'(\p{L})/gu, (_, c: string) => `-l'${c.toUpperCase()}`)
    .replace(/\bIj/g, "IJ");
  return name;
}

function parseCsvLine(line: string): string[] {
  const out: string[] = [];
  let current = "";
  let quoted = false;
  for (const char of line) {
    if (char === '"') quoted = !quoted;
    else if (char === "," && !quoted) {
      out.push(current);
      current = "";
    } else current += char;
  }
  out.push(current);
  return out;
}

async function main() {
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`Download failed: ${response.status}`);
  const lines = (await response.text()).trim().split(/\r?\n/).slice(1);
  const seen = new Set<string>();
  const rows: string[] = [];
  for (const line of lines) {
    const [postal, name, lat, lng] = parseCsvLine(line);
    const latitude = Number(lat);
    const longitude = Number(lng);
    if (!postal || !name || !Number.isFinite(latitude) || !Number.isFinite(longitude)) {
      continue;
    }
    const row = `${postal}|${cleanName(name)}|${latitude.toFixed(4)}|${longitude.toFixed(4)}`;
    if (seen.has(row)) continue;
    seen.add(row);
    rows.push(row);
  }
  const body = `/**
 * Belgian postcode places (municipalities and deelgemeenten) with coordinates.
 * Generated by scripts/build-be-places.ts. Do not edit by hand.
 * Source: spatie/belgian-cities-geocoded (MIT, © Spatie bvba).
 * Format: one "postcode|name|lat|lng" per line.
 */
export const BE_PLACES_RAW = \`
${rows.join("\n")}
\`;
`;
  writeFileSync(join(__dirname, "..", "data", "be-places.ts"), body);
  console.log(`Wrote ${rows.length} places`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
