export type Phase4BatchItem = {
  event: Event;
  decision: PreviewImportDecision;
};

function item(
  event: Event,
  decision: Omit<PreviewImportDecision, "previewId" | "slug"> & {
    previewId?: string;
    slug?: string;
  },
): Phase4BatchItem {
  const previewId = decision.previewId ?? event.id;
  const slug = decision.slug ?? event.slug;
  return {
    event,
    decision: {
      ...decision,
      previewId,
      slug,
    },
  };
}

